from zj_datagen import gen

NOT_FETCHED = "nicht abgerufen / not fetched yet (`task data:fetch`)"


def _manifest(p: Path) -> dict[str, Any] | None:
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def _table(rows: list[list[Any]], header: list[str]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def _pct(x: float) -> str:
    return f"{100 * x:.2f} %"


def _files(synth: Path, table: str) -> tuple[str, dict[str, Any] | None]:
    rows: list[list[Any]] = []
    largest: dict[str, Any] | None = None
    for scale in gen.SCALES:
        m = _manifest(synth / table / scale / "manifest.json")
        if m is None:
            rows.append([scale, "nicht generiert / not generated", "", ""])
            continue
        largest = m
        csv = m["files"]["cp1252.csv"]
        rows.append([scale, f"{m['rows']:,}".replace(",", " "), f"{csv['bytes'] / 1e6:.1f} MB",
                     f"`{csv['sha256'][:16]}…`"])  # fmt: skip
    return _table(rows, ["Skala / scale", "Zeilen / rows", "cp1252.csv", "sha256 (cp1252.csv)"]), largest


def _noise_stats(con: duckdb.DuckDBPyConnection, gold: Path, keys: list[str]) -> str:
    n = con.execute("SELECT count(*) FROM read_parquet(?)", [str(gold)]).fetchone()
    assert n is not None
    rows: list[list[Any]] = []
    for k in keys:
        r = con.execute(
            "SELECT count(*) FROM read_parquet(?) WHERE list_contains(string_split(noise, ','), ?)",
            [str(gold), k],
        ).fetchone()
        assert r is not None
        rows.append([k, _pct(r[0] / n[0])])
    return _table(rows, ["Rauschen / noise", "gemessen / measured"])


