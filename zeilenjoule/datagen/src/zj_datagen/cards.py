def real_card(repo: Path, src: str) -> str:
    name, who, url, terms, privacy = REAL[src]
    m = _manifest(repo / "data" / "real" / src / "manifest.json")
    status = (
        NOT_FETCHED
        if m is None
        else f"{m['rows']} Zeilen / rows ({m['network_requests']} Anfragen, {m['cache_hits']} aus Cache)"
    )
    lines = [
        f"# Datensatzkarte / Dataset card: `{name}` (real)",
        "",
        "> Generiert von `task data:cards`.",
        "",
        f"- **Quelle / source:** {who}: {url}",
        f"- **Bedingungen / terms:** {terms}",
        f"- **Datenschutz / privacy (Regel 8):** {privacy}",
        "- **Abruf / fetching:** ≤ 1 Anfrage/s, User-Agent `zeilenjoule-research/0.1`, Rohantworten in `data/raw/`.",
        f"- **Stand / status:** {status}",
    ]
    if m:
        lines += ["", "```json", json.dumps(m, indent=2, ensure_ascii=False), "```"]
    return "\n".join(lines) + "\n"


