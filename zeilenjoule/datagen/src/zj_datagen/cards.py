def write_all(repo: Path) -> list[Path]:
    out = repo / "data" / "cards"
    out.mkdir(parents=True, exist_ok=True)
    cards = {
        "stoermeldungen.md": stoermeldungen_card(repo),
        "qualitaetsmeldungen.md": qualitaet_card(repo),
        "evaluationssets.md": eval_sets_card(repo),
        **{f"{REAL[s][0]}.md": real_card(repo, s) for s in REAL},
        "real_nrw_corpus.md": real_corpus_card(repo),
    }
    paths: list[Path] = []
    for fname, text in cards.items():
        (out / fname).write_text(text, encoding="utf-8")
        paths.append(out / fname)
    return paths
