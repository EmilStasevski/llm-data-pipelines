        "sampled first and German text is rendered from them, so every row has ground truth.",
        "",
        "**Lizenz / licence:** synthetisch, vom Projekt erzeugt; keine personenbezogenen Daten, keine realen "
        "Unternehmen. / synthetic, generated by this project; no personal data, no real companies.",
        "",
        "## Dateien / files",
        files,
        "",
        "Pro Skala / per scale: `stoermeldungen.cp1252.csv` (`;`, Dezimalkomma, CRLF), `stoermeldungen.utf8.csv` "
        "(LF), `stoermeldungen.parquet` (sichtbare Spalten als Strings, zstd), `stoermeldungen_gold.parquet` "
        "(typisierte Gold-Labels), `manifest.json`; bei S zusätzlich `stoermeldungen_sample.xlsx` (1 000 Zeilen).",
        "",
