@dataclass(frozen=True)
class Bar:
    label: str
    value: float
    text: str
    anti: bool = False


def esc(s: str) -> str:
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def ticks_log(lo: float, hi: float) -> list[float]:
    out: list[float] = []
    for e in range(math.floor(math.log10(lo)), math.ceil(math.log10(hi)) + 1):
        out += [m * 10.0**e for m in (1, 2, 5) if lo <= m * 10.0**e <= hi]
    return out


def nice(v: float, *, down: bool) -> float:
    """Nearest 1-2-5 step at or below (down) / at or above v."""
    e = math.floor(math.log10(v))
    steps = [m * 10.0**k for k in (e - 1, e, e + 1) for m in (1, 2, 5)]
    return max(s for s in steps if s <= v) if down else min(s for s in steps if s >= v)


def tick_label(v: float) -> str:
    return f"{v:g}" if v < 1e4 else f"{v / 1e3:g}k"


def svg_bars(title: str, bars: list[Bar], *, log: bool = True) -> str:
    """Horizontal single-series bar chart; value labels in ink at the bar end (marks carry no text color)."""
    w, left, right, top, row = 820, 200, 150, 34, 24
    h = top + row * len(bars) + 30
    plot = w - left - right
    vals = [b.value for b in bars]
    lo = nice(min(vals), down=True) if log else 0.0
    hi = nice(max(vals), down=False) if log else max(vals) * 1.05

    def x(v: float) -> float:
        if log:
            return left + plot * (math.log10(v) - math.log10(lo)) / (math.log10(hi) - math.log10(lo))
        return left + plot * v / hi

    ticks = ticks_log(lo, hi) if log else [hi / 4 * i for i in range(5)]
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}" '
           f'role="img" aria-label="{esc(title)}"><style>{CSS}</style>',
           f'<rect class="bg" width="{w}" height="{h}" rx="6"/>',
           f'<text class="ink" x="16" y="20" font-weight="600">{esc(title)}</text>']  # fmt: skip
    yb = top + row * len(bars)
    for t in ticks:
        out.append(f'<line class="grid" x1="{x(t):.1f}" x2="{x(t):.1f}" y1="{top - 4}" y2="{yb}"/>')
        out.append(
            f'<text class="mut" x="{x(t):.1f}" y="{yb + 16}" text-anchor="middle">{tick_label(t)}</text>'
        )
    out.append(f'<line class="axis" x1="{left}" x2="{left}" y1="{top - 4}" y2="{yb}"/>')
    for i, b in enumerate(bars):
        y = top + i * row
        x1 = max(x(b.value), left + 4)
        cls = "anti" if b.anti else "s1"
        out.append(
            f'<text class="sec mono" x="{left - 8}" y="{y + 15}" text-anchor="end">{esc(b.label)}</text>'
        )
        out.append(
            f'<path class="{cls}" d="M{left},{y + 4}H{x1 - 4:.1f}a4,4 0 0 1 4,4v6a4,4 0 0 1 -4,4H{left}Z"/>'
        )
        out.append(f'<text class="ink" x="{x1 + 6:.1f}" y="{y + 15}">{esc(b.text)}</text>')
    out.append("</svg>")
    return "\n".join(out) + "\n"


def svg_grouped(
    title: str, labels: list[str], series: tuple[list[float], list[float]], names: tuple[str, str], lang: str
) -> str:
    """Two-series horizontal grouped bars (linear axis, legend + direct value labels)."""
    w, left, right, top, row = 820, 200, 70, 56, 30
    h = top + row * len(labels) + 30
    plot = w - left - right
    a, b = series
    hi = max(a + b) * 1.05
    step = 10 ** math.floor(math.log10(hi / 4))
    step = next(m * step for m in (1, 2, 5, 10) if hi / (m * step) <= 6)

    def x(v: float) -> float:
        return left + plot * v / hi

    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}" '
           f'role="img" aria-label="{esc(title)}"><style>{CSS}</style>',
           f'<rect class="bg" width="{w}" height="{h}" rx="6"/>',
           f'<text class="ink" x="16" y="20" font-weight="600">{esc(title)}</text>',
           f'<rect class="s1" x="16" y="30" width="10" height="10" rx="2"/>'
           f'<text class="sec" x="32" y="39">{esc(names[0])}</text>',
           f'<rect class="s2" x="130" y="30" width="10" height="10" rx="2"/>'
           f'<text class="sec" x="146" y="39">{esc(names[1])}</text>']  # fmt: skip
    yb = top + row * len(labels)
    t = 0.0
    while t <= hi:
        out.append(f'<line class="grid" x1="{x(t):.1f}" x2="{x(t):.1f}" y1="{top - 4}" y2="{yb}"/>')
        out.append(f'<text class="mut" x="{x(t):.1f}" y="{yb + 16}" text-anchor="middle">{t:g}</text>')
        t += step
    out.append(f'<line class="axis" x1="{left}" x2="{left}" y1="{top - 4}" y2="{yb}"/>')
    for i, lab in enumerate(labels):
        y = top + i * row
        out.append(f'<text class="sec mono" x="{left - 8}" y="{y + 18}" text-anchor="end">{esc(lab)}</text>')
        for j, (v, cls) in enumerate(((a[i], "s1"), (b[i], "s2"))):
            yy = y + 3 + j * 12  # 10 px bars, 2 px surface gap
            x1 = max(x(v), left + 3)
            out.append(
                f'<path class="{cls}" d="M{left},{yy}H{x1 - 3:.1f}a3,3 0 0 1 3,3v4a3,3 0 0 1 -3,3H{left}Z"/>'
            )
            out.append(
                f'<text class="ink" x="{x1 + 4:.1f}" y="{yy + 9}" font-size="10">{fmt_num(v, 0, lang)}</text>'
            )
    out.append("</svg>")
    return "\n".join(out) + "\n"


def _rows(con: duckdb.DuckDBPyConnection, section: str, scale: str) -> list[Summary]:
    return sorted((s for s in summaries(con, section) if s.scale == scale), key=lambda s: s.wall)


def _qps(con: duckdb.DuckDBPyConnection, scale: str) -> dict[str, tuple[float, float]]:
    acc: dict[str, dict[str, list[float]]] = {}
    for c, sc, st, ex, q, rows in con.execute(DETAIL_SQL, list(section_filter("C"))).fetchall():
        if sc == scale:
            accumulate(acc.setdefault(str(c), {}), st, ex, q, rows)
    out: dict[str, tuple[float, float]] = {}
    for c, d in acc.items():
        a, b = median_of(d.get("qps_c1", [])), median_of(d.get("qps_c16", []))
        if a is not None and b is not None:
            out[c] = (a, b)
    return out


def _quality_e(con: duckdb.DuckDBPyConnection, scale: str) -> dict[str, float]:
    """Median overall answer quality per Track E contestant at `scale` (spec/track_e.md)."""
    acc: dict[str, dict[str, list[float]]] = {}
    for c, sc, st, ex, q, rows in con.execute(DETAIL_SQL, list(section_filter("E"))).fetchall():
        if sc == scale:
            accumulate(acc.setdefault(str(c), {}), st, ex, q, rows)
    return {c: v for c, d in acc.items() if (v := median_of(d.get("overall", []))) is not None}


def quality_d(con: duckdb.DuckDBPyConnection, scale: str) -> dict[str, tuple[float, float]]:
    """Median macro-F1 and JSON validity per Track D contestant at `scale`."""
    acc: dict[str, dict[str, list[float]]] = {}
    for c, sc, st, ex, q, rows in con.execute(DETAIL_SQL, list(section_filter("D"))).fetchall():
        if sc == scale:
            accumulate(acc.setdefault(str(c), {}), st, ex, q, rows)
    out: dict[str, tuple[float, float]] = {}
    for c, d in acc.items():
        f1, ok = median_of(d.get("macro_f1", [])), median_of(d.get("json_validity", []))
        if f1 is not None and ok is not None:
            out[c] = (f1, ok)
    return out


def _value_text(s: Summary, lang: str) -> str:
    e = f" · {fmt_num(s.e_gross, 0 if s.e_gross >= 100 else 1, lang)} J" if s.e_gross is not None else ""
    return f"{fmt_num(s.wall, 2 if s.wall < 100 else 0, lang)} s{e}"


def block(con: duckdb.DuckDBPyConnection, figs: Path, lang: str) -> str:
    t = TXT[lang]
    out = [BEGIN, f"## {t['title']}", "", t["note"], ""]
    for section, scale, stem in HIGHLIGHTS:
        rows = _rows(con, section, scale)
        if not rows:
            continue
        title, units, _, _ = TRACKS[section][lang]
        head = f"{title}: {t['scale']} {scale} ({fmt_num(float(rows[0].rows), 0, lang)} {units})"
        out += [f"### {head}", ""]
        if stem and len(rows) > 1:
            bars = [Bar(s.contestant, s.wall, _value_text(s, lang), s.anti) for s in rows]
            (figs / f"{stem}.{lang}.svg").write_text(svg_bars(t["wall"], bars), encoding="utf-8")
            out += [f"![{esc(head)}](reports/figures/{stem}.{lang}.svg)", ""]
        body: list[list[str]] = []
        for i, s in enumerate(rows, 1):
            ratio = s.wall / rows[0].wall
            name = f"`{s.contestant}`" + (f" ({t['anti']})" if s.anti else "")
            if s.contestant in PRODUCTION_STACKS:
                name += f" ({t['stack']})"
            body.append([str(i), name, fmt_num(s.wall, 2, lang), fmt_num(ratio, 2 if ratio < 10 else 0, lang),
                         fmt_num(s.e_gross, 1, lang)])  # fmt: skip
        head_cells = HEAD[lang]
        if section == "D" and (q := quality_d(con, scale)):  # Track D: quality decides as much as speed
            best = max(f1 for f1, _ in q.values())
            head_cells = [*head_cells, "macro-F1", t["gate"]]
            for r, s in zip(body, rows, strict=True):
                f1, ok = q.get(s.contestant, (None, None))
                passed = f1 is not None and ok is not None and f1 >= WINNER_F1 * best and ok >= 0.995
                r += [fmt_num(f1, 3, lang), "✓" if passed else "✗"]
        if section == "E" and (qe := _quality_e(con, scale)):  # gate over the candidates only (ADR 0025)
            best = max((v for c, v in qe.items() if c not in PRODUCTION_STACKS), default=None)
            head_cells = [*head_cells, t["overall"], t["gate"]]
            for r, s in zip(body, rows, strict=True):
                v = qe.get(s.contestant)
                r += [fmt_num(v, 3, lang), "✓" if v is not None and best and v >= WINNER_F1 * best else "✗"]
        out += ["| " + " | ".join(head_cells) + " |", "|" + "---|" * len(head_cells)]
        out += ["| " + " | ".join(r) + " |" for r in body] + [""]
        if section == "C" and (qps := _qps(con, scale)):
            order = sorted(qps, key=lambda c: -qps[c][1])
            series = ([qps[c][0] for c in order], [qps[c][1] for c in order])
            svg = svg_grouped(t["c16"], order, series, (t["c1"], t["c16l"]), lang)  # fmt: skip
            (figs / f"track_c_qps_{scale}.{lang}.svg").write_text(svg, encoding="utf-8")
            out += [f"![{t['c16']}](reports/figures/track_c_qps_{scale}.{lang}.svg)", ""]
    return "\n".join([*out, END])


def update(repo: Path, con: duckdb.DuckDBPyConnection) -> list[str]:
    """Rewrite the results block in README.md / README.de.md (inserted before '## Quick start' if absent)."""
    figs = repo / "reports" / "figures"
    figs.mkdir(parents=True, exist_ok=True)
    done: list[str] = []
    for lang, name, anchor in (
        ("en", "README.md", "## Quick start"),
        ("de", "README.de.md", "## Schnellstart"),
    ):
        path = repo / name
        if not path.exists():
            continue
        text = path.read_text(encoding="utf-8")
        new = block(con, figs, lang)
        if BEGIN in text and END in text:
            text = text[: text.index(BEGIN)] + new + text[text.index(END) + len(END) :]
        elif anchor in text:
            text = text.replace(anchor, f"{new}\n\n{anchor}", 1)
        else:
            text = text.rstrip("\n") + f"\n\n{new}\n"
        path.write_text(text, encoding="utf-8")
        done.append(name)
    return done


def has_runs(con: duckdb.DuckDBPyConnection) -> bool:
    r: Any = con.execute(
        "SELECT count(*) FROM information_schema.tables WHERE table_name = 'ok_runs'"
    ).fetchone()
    return bool(r and r[0])
